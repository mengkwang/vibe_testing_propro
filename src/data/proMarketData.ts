// Helper to generate realistic Candlestick Data for Modal
export function generateCandlesticks(
  symbol: string,
  basePrice: number,
  isBullish: boolean,
  count: number = 32
): CandlestickData[] {
  const candles: CandlestickData[] = [];
  let currentPrice = basePrice * (isBullish ? 0.94 : 1.05);

  const now = Date.now();
  const stepMs = 5 * 60 * 1000; // 5 min candles

  for (let i = 0; i < count; i++) {
    const timeObj = new Date(now - (count - i) * stepMs);
    const timeStr = `${String(timeObj.getHours()).padStart(2, '0')}:${String(timeObj.getMinutes()).padStart(2, '0')}`;

    const trendBias = isBullish ? 0.0015 : -0.0012;
    const volatility = 0.006;
    const delta = (Math.random() - 0.48 + trendBias) * volatility;

    const open = currentPrice;
    const close = Math.max(1, open * (1 + delta));
    const highWick = Math.random() * 0.004;
    const lowWick = Math.random() * 0.004;
    const high = Math.max(open, close) * (1 + highWick);
    const low = Math.min(open, close) * (1 - lowWick);

    const volume = Math.floor(25000 + Math.random() * 120000);

    // Calculate moving average
    let sma = open;
    if (candles.length > 5) {
      const slice = candles.slice(-5);
      const sum = slice.reduce((acc, c) => acc + c.close, close);
      sma = sum / (slice.length + 1);
    }

    // Pseudo RSI
    const rsi = isBullish ? 55 + Math.sin(i * 0.4) * 15 : 45 - Math.cos(i * 0.4) * 15;

    candles.push({
      time: timeStr,
      open: parseFloat(open.toFixed(2)),
      high: parseFloat(high.toFixed(2)),
      low: parseFloat(low.toFixed(2)),
      close: parseFloat(close.toFixed(2)),
      volume,
      sma: parseFloat(sma.toFixed(2)),
      rsi: Math.round(rsi),
    });

    currentPrice = close;
  }

  return candles;
}

